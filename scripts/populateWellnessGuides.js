function slugify(s) {
  return String(s).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}
function docIdFor(entry) {
  const tail = entry.code ? slugify(entry.code) : slugify(entry.title);
  return `${entry.category}-${tail}`.slice(0, 120);
}

// body-র শব্দ-সংখ্যা: [MORE] ও রেফারেন্স-অংশ ("▌ রেফারেন্স" থেকে শেষ) বাদ; শুধু অক্ষর/অঙ্কযুক্ত টোকেন গোনা হয়।
const MIN_WORDS = 500;
function bodyWordCount(body) {
  let text = String(body || "").replace("[MORE]", " ");
  const refAt = text.search(/^▌\s*রেফারেন্স/m);
  if (refAt !== -1) text = text.slice(0, refAt);
  return text.split(/\s+/).filter((t) => /[\p{L}\p{N}]/u.test(t)).length;
}

